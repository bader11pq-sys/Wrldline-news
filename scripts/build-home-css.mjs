#!/usr/bin/env node
/**
 * WRLDLINE homepage stylesheet bundle.
 *
 * The homepage used to request nine render-blocking stylesheets (about 152 KB of
 * CSS) before it could paint. They are plain CSS with no @import, no @charset and
 * no url() references, so concatenating them in the exact order the page linked
 * them is behaviour-preserving: the cascade order is identical.
 *
 * The bundle is generated, never hand-edited. `--check` fails when the committed
 * bundle no longer matches its sources, so the two cannot drift apart silently.
 *
 * Usage: node scripts/build-home-css.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCES = [
  "wrld.css",
  "site-enhancements.css",
  "intelligence.css",
  "homepage-polish.css",
  "wl-modern.css",
  "newsroom-edition.css",
  "editorial-launch.css",
  "front-page.css",
  "rights-front.css"
];
export const OUTPUT = "home.bundle.css";

/** @param {string} [root] @returns {string} */
export function bundle(root = ROOT) {
  const parts = SOURCES.map(name => {
    const css = fs.readFileSync(path.join(root, name), "utf8");
    if (/@import|@charset/i.test(css)) throw new Error(`${name} cannot be bundled: it contains @import or @charset`);
    return `/* ${name} */\n${css.trim()}\n`;
  });
  return `/* WRLDLINE homepage bundle. Generated by scripts/build-home-css.mjs — do not edit by hand. */\n${parts.join("\n")}`;
}

export function run(argv = process.argv.slice(2)) {
  const check = argv.includes("--check");
  const target = path.join(ROOT, OUTPUT);
  const next = bundle();
  if (check) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current !== next) {
      console.error(`${OUTPUT} is stale. Run: node scripts/build-home-css.mjs`);
      return 1;
    }
    console.log(`${OUTPUT} is up to date (${Buffer.byteLength(next)} bytes).`);
    return 0;
  }
  fs.writeFileSync(target, next);
  console.log(`Wrote ${OUTPUT} (${Buffer.byteLength(next)} bytes from ${SOURCES.length} sources).`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = run();
}
