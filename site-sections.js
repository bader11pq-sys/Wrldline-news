  /* Everything readers can navigate to, flattened once. */
  const ALL_LINKS = [];
  const BY_KEY = new Map();
  const seenHref = new Set();

  function add(item, groupKey) {
    if (!item || !item.key) throw new Error("Registry item without a key");
    if (BY_KEY.has(item.key)) throw new Error("Duplicate registry key: " + item.key);
    if (!item.href) throw new Error("Registry item without href: " + item.key);
    if (!item.ar || !item.en) throw new Error("Registry item without bilingual label: " + item.key);
    if (seenHref.has(item.href)) throw new Error("Duplicate navigation destination: " + item.href);
    seenHref.add(item.href);
    const entry = Object.assign({}, item, { group: groupKey, children: [] });
    BY_KEY.set(item.key, entry);
    ALL_LINKS.push(entry);
    return entry;
  }

  Object.values(CORE_LINKS).forEach(item => add(item, "core"));
  for (const section of NEWS_SECTIONS) {
    add(section, "news");
    for (const child of section.children) {
      add(child, section.key);
      BY_KEY.get(section.key).children.push(child.key);
    }
  }
  for (const group of KNOWLEDGE_GROUPS) group.items.forEach(item => add(item, group.key));
  TOOL_GROUP.items.forEach(item => add(item, TOOL_GROUP.key));
  SERVICE_GROUP.items.forEach(item => add(item, SERVICE_GROUP.key));
  SITE_GROUP.items.forEach(item => add(item, SITE_GROUP.key));

  function item(key) {
    const found = BY_KEY.get(String(key || ""));
    if (!found) throw new Error("Unknown navigation key: " + key);
    return found;
  }
  function pick(keys) { return keys.map(item); }

